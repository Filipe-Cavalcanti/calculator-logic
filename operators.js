function sum (num1, num2) {
    return num1 + num2
};

function minus (num1, num2) {
    return num1 - num2
};

function division (num1, num2) {
    return num1 / num2
};

function multiplication (num1, num2) {
    return num1 * num2
};

console.log(sum(4, 5));
console.log(minus(4, 5));
console.log(division(4, 4));
console.log(multiplication(4, 5));
